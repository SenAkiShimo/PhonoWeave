"""Matched-line-count audit of literal and speaker-context recording policies.

Uses the EXACT same pitch-complete reference recordings for both policies.
All acoustic/phonetic interpretations remain the existing, provisional Mandarin
speaker-context proxy. Neither selection nor comparison authorizes recordings.
"""
from __future__ import annotations

import csv
from hashlib import sha256
import io
import json
import os
from pathlib import Path
import tempfile

from .reclist import parse_reclist
from .reclist_budget import plan_literal_budget
from .recording_scheme_budget import _eligible_source
from .speaker_context_budget import (
    CONFIDENCE_WEIGHTS, _counts, _reference_evidence,
    compile_speaker_context_budget,
)

SCHEMA = "phonoweave.matched_budget_literal_audit.v0.1"
PACK_SCHEMA = "phonoweave.recording_review_pack.v0.1"
SOURCE_FILES = (
    "reference/reference_reclist_blueprint.json",
    "budget/speaker_context_budget_plan.json",
    "scheme/recording_units_review.csv",
    "scheme/internal_context_links.csv",
)


def _metrics(names: list[str], eligible: dict, features: dict,
             goals: dict, weights: dict, universe: dict) -> dict:
    union = {
        key: set().union(*(eligible[name]["features"][key] for name in names))
        if names else set()
        for key in universe
    }
    depths = _counts(names, features)
    return {
        "lines_per_pitch": len(names),
        "source_wav_references": sum(len(eligible[name]["sources"]) for name in names),
        "surface_types": {
            key: {"covered": len(union[key]), "total": len(universe[key])}
            for key in universe
        },
        "provisional_context_pitch_cells_with_reference": sum(
            depths[cell] > 0 for cell in goals),
        "provisional_context_pitch_cells_meeting_feasible_target": sum(
            depths[cell] >= target for cell, target in goals.items()),
        "provisional_context_pitch_cells_total": len(goals),
        "weighted_provisional_context_depth": sum(
            weights[cell] * min(depths[cell], target)
            for cell, target in goals.items()),
    }


def compare_literal_budget(
    blueprint: dict, speaker_plan: dict, unit_rows: list[dict],
    link_rows: list[dict], *, token_weight: int = 1, pair_weight: int = 2,
) -> dict:
    """Compute comparisons without confusing budget ceilings with equal costs.

    Recompile the speaker policy from the provided evidence and require exact
    equality, preventing stale or manually modified selections from being
    compared as though they were generated by the current code.
    """
    if speaker_plan.get("schema") != "phonoweave.speaker_context_budget_plan.v0.1":
        raise ValueError("unsupported speaker context plan")
    budget = speaker_plan.get("per_pitch_line_budget_max")
    repeat = speaker_plan.get("repeat_target_per_unit_pitch")
    verified = compile_speaker_context_budget(
        blueprint, unit_rows, link_rows, budget, repeat_target=repeat)
    if verified != speaker_plan:
        raise ValueError("speaker plan differs from recomputed source evidence")
    pitches, eligible, excluded = _eligible_source(blueprint)

    # The exact shared reference candidate set is fixed BEFORE either policy
    # is compared. The ordering is canonical and independent of input rows.
    names = sorted(eligible)
    text_source = "\n".join(names) + ("\n" if names else "")
    document = parse_reclist(text_source, separator="underscore")
    literal_plan = plan_literal_budget(
        document, budget, token_weight=token_weight, pair_weight=pair_weight)
    literal = [row["raw"] for row in literal_plan["selected_lines"]]
    speaker = speaker_plan["selection"]["selected_lines"]
    if (len(set(speaker)) != len(speaker)
            or any(name not in eligible for name in speaker)
            or any(name not in eligible for name in literal)):
        raise ValueError("policy references an ineligible or duplicate source")
    if len(speaker) > budget or len(literal) > budget:
        raise ValueError("policy exceeds recording line budget")

    evidence, units, omitted, ignored, accepted = _reference_evidence(
        eligible, unit_rows, link_rows, pitches)
    total_depth = _counts(names, evidence)
    goals = {cell: min(repeat, count) for cell, count in total_depth.items()}
    weights = {
        cell: CONFIDENCE_WEIGHTS[units[cell[0]]["confidence"]]
        for cell in goals
    }
    universe = {
        key: set().union(*(item["features"][key] for item in eligible.values()))
        if eligible else set()
        for key in ("syllables", "starts", "exact_adjacent_pairs")
    }
    common = min(len(speaker), len(literal))
    curve = []
    for k in range(common + 1):
        sm = _metrics(speaker[:k], eligible, evidence, goals, weights, universe)
        lm = _metrics(literal[:k], eligible, evidence, goals, weights, universe)
        curve.append({
            "matched_lines_per_pitch": k,
            "speaker": sm,
            "literal": lm,
            "speaker_minus_literal_weighted_depth": (
                sm["weighted_provisional_context_depth"]
                - lm["weighted_provisional_context_depth"]),
        })
    return {
        "schema": SCHEMA,
        "status": "review_only_no_synthesis_or_perceptual_validation",
        "source": {
            "blueprint_schema": blueprint["schema"],
            "speaker_plan_schema": speaker_plan["schema"],
            "pitch_groups": pitches,
            "pitch_complete_reference_lines": len(names),
            "excluded_reference_lines": len(excluded),
            "accepted_internal_candidate_links": accepted,
            "ignored_links_outside_reference": ignored,
            "unoptimized_inventory_units": sorted(omitted),
        },
        "settings": {
            "max_lines_per_pitch": budget,
            "speaker_repeat_target": repeat,
            "literal_token_weight": token_weight,
            "literal_pair_weight": pair_weight,
            "canonical_reference_order": "lexicographic",
            "equal_budget_basis": "exact_prefix_line_count_per_pitch",
        },
        "policies": {
            "speaker": {
                "name": speaker_plan["selection"]["policy"],
                "selected_sequences": speaker,
                "max_budget_result": _metrics(
                    speaker, eligible, evidence, goals, weights, universe),
            },
            "literal": {
                "name": "surface_token_pair_weighted_greedy",
                "selected_sequences": literal,
                "max_budget_result": _metrics(
                    literal, eligible, evidence, goals, weights, universe),
            },
        },
        "matched_curve": curve,
        "matched_prefix_count": common,
        "different_final_line_counts": len(speaker) != len(literal),
        "comparison_limits": [
            "Only exact common-prefix line counts are paired; unequal final "
            "line counts must not be described as equal-cost comparisons.",
            "One selected sequence means one source WAV in each pitch group, "
            "not an independently repeated take or measured recording duration.",
            "Literal adjacent tokens are NOT automatically phonemes, CV or VC "
            "events, or verified OTO boundaries.",
            "Speaker-policy context evidence is provisional and Mandarin "
            "specific; protected splits are NOT validated synthesis gains.",
            "All source candidates are from existing pitch-complete WAV and "
            "OTO references; no unseen recordings were generated.",
            "This is in-sample acquisition planning, not held-out speaker, "
            "rendered singing, listening, or perceptual validation.",
        ],
        "production_ready": False,
        "production_alias_export": "disabled",
        "oto_timing_changes": "none",
        "recordings_authorized": 0,
    }


def load_verified_review_pack(pack: Path) -> tuple[dict, dict, list[dict], list[dict], dict]:
    """Reject modified artifacts, traversal and symlink escapes before analysis."""
    root = pack.expanduser().resolve(strict=True)
    if not root.is_dir():
        raise ValueError("review pack path must be a directory")
    manifest_path = root / "review_pack_manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("schema") != PACK_SCHEMA:
        raise ValueError("unsupported review pack manifest")
    hashes = manifest.get("artifact_sha256")
    if not isinstance(hashes, dict):
        raise ValueError("review pack has no artifact hashes")

    data = {}
    for rel in SOURCE_FILES:
        path = root / rel
        resolved = path.resolve(strict=True)
        if not resolved.is_relative_to(root) or not resolved.is_file():
            raise ValueError("pack source file escapes review directory")
        expected = hashes.get(rel)
        if not isinstance(expected, str) or len(expected) != 64:
            raise ValueError(f"review pack lacks hash for {rel}")
        raw = resolved.read_bytes()
        if sha256(raw).hexdigest() != expected:
            raise ValueError(f"review pack source hash mismatch: {rel}")
        data[rel] = raw.decode("utf-8")
    blueprint = json.loads(data[SOURCE_FILES[0]])
    speaker = json.loads(data[SOURCE_FILES[1]])
    units = list(csv.DictReader(io.StringIO(data[SOURCE_FILES[2]])))
    links = list(csv.DictReader(io.StringIO(data[SOURCE_FILES[3]])))
    return blueprint, speaker, units, links, {
        "manifest_schema": manifest["schema"],
        "source_artifact_sha256": {rel: hashes[rel] for rel in SOURCE_FILES},
    }


def write_comparison(result: dict, output: Path) -> Path:
    """Publish an atomic, non-overwriting research audit outside source pack."""
    output = output.expanduser().resolve()
    if output.exists():
        raise FileExistsError(f"destination exists: {output}")
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(
        prefix=".phonoweave-literal-compare-", dir=output.parent,
    ) as temp:
        stage = Path(temp) / "report"
        stage.mkdir()
        (stage / "matched_budget_comparison.json").write_text(
            json.dumps(result, ensure_ascii=False, indent=2, allow_nan=False) + "\n",
            encoding="utf-8",
        )
        (stage / "literal_baseline_reclist.txt").write_text(
            "".join(line + "\n" for line in
                    result["policies"]["literal"]["selected_sequences"]),
            encoding="utf-8",
        )
        with (stage / "matched_curve.csv").open("w", newline="", encoding="utf-8") as stream:
            columns = [
                "matched_lines_per_pitch", "speaker_surface_tokens",
                "literal_surface_tokens", "speaker_adjacent_pairs",
                "literal_adjacent_pairs", "speaker_weighted_context_depth",
                "literal_weighted_context_depth", "speaker_minus_literal_depth",
            ]
            writer = csv.DictWriter(stream, fieldnames=columns)
            writer.writeheader()
            for row in result["matched_curve"]:
                s, l = row["speaker"], row["literal"]
                writer.writerow({
                    "matched_lines_per_pitch": row["matched_lines_per_pitch"],
                    "speaker_surface_tokens": s["surface_types"]["syllables"]["covered"],
                    "literal_surface_tokens": l["surface_types"]["syllables"]["covered"],
                    "speaker_adjacent_pairs": s["surface_types"]["exact_adjacent_pairs"]["covered"],
                    "literal_adjacent_pairs": l["surface_types"]["exact_adjacent_pairs"]["covered"],
                    "speaker_weighted_context_depth": s["weighted_provisional_context_depth"],
                    "literal_weighted_context_depth": l["weighted_provisional_context_depth"],
                    "speaker_minus_literal_depth": row["speaker_minus_literal_weighted_depth"],
                })
        if output.exists():
            raise FileExistsError("destination appeared during compilation")
        os.rename(stage, output)
    return output
